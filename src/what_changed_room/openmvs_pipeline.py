def reconstruct_openmvs_cpu(
    shared_model: str | Path,
    before_images: str | Path,
    after_images: str | Path,
    object_report: str | Path,
    openmvs_bin: str | Path,
    output_dir: str | Path,
    *,
    max_threads: int = 8,
    meters_per_map_unit: float | None = None,
) -> dict[str, object]:
    """Build separate CPU dense clouds and textured meshes in one shared frame."""
    model_dir, before_dir, after_dir = map(
        lambda value: Path(value).resolve(), (shared_model, before_images, after_images)
    )
    tools = Path(openmvs_bin).resolve()
    output = Path(output_dir).resolve()
    if not model_dir.is_dir() or not before_dir.is_dir() or not after_dir.is_dir():
        raise NotADirectoryError("shared model and both source image directories must exist")
    if max_threads < 1:
        raise ValueError("max_threads must be at least 1")
    if meters_per_map_unit is not None and meters_per_map_unit <= 0:
        raise ValueError("meters_per_map_unit must be positive")
    if output.exists() and any(output.iterdir()):
        raise FileExistsError(f"output directory is not empty: {output}")
    output.mkdir(parents=True, exist_ok=True)
    tool = {name: _find_tool(tools, name) for name in (
        "InterfaceCOLMAP", "DensifyPointCloud", "ReconstructMesh", "RefineMesh", "TextureMesh", "Viewer"
    )}

    cameras = _read_colmap_cameras(model_dir)
    images = _read_images(model_dir / "images.bin")
    points = _read_sparse_points(model_dir / "points3D.bin")
    counts: dict[str, object] = {}
    commands: list[list[str]] = []
    log = output / "openmvs.log"
    for capture, source_dir in (("before", before_dir), ("after", after_dir)):
        scene_dir = output / capture
        scene_dir.mkdir()
        sparse_points = _write_capture_input(
            capture, model_dir, source_dir, scene_dir, cameras, images, points
        )
        counts[f"{capture}_images"] = sum(
            _capture_for_image(name) == capture for name in images
        )
        counts[f"{capture}_sparse_points"] = sparse_points
        scene_mvs = scene_dir / "scene.mvs"
        dense_mvs = scene_dir / "scene_dense.mvs"
        mesh_ply = scene_dir / "scene_mesh.ply"
        refined_ply = scene_dir / "scene_mesh_refine.ply"
        textured_ply = scene_dir / "scene_textured.ply"
        stage_commands = [
            [str(tool["InterfaceCOLMAP"]), "--input-file", str(scene_dir), "--output-file", str(scene_mvs), "--image-folder", str(scene_dir / "images")],
            [str(tool["DensifyPointCloud"]), "--input-file", str(scene_mvs), "--output-file", str(dense_mvs), "--fusion-mode", "0", "--max-threads", str(max_threads)],
            [str(tool["ReconstructMesh"]), "--input-file", str(dense_mvs), "--output-file", str(mesh_ply), "--max-threads", str(max_threads)],
            [str(tool["RefineMesh"]), "--input-file", str(dense_mvs), "--mesh-file", str(mesh_ply), "--output-file", str(refined_ply), "--resolution-level", "1", "--max-threads", str(max_threads)],
            [str(tool["TextureMesh"]), "--input-file", str(dense_mvs), "--mesh-file", str(refined_ply), "--output-file", str(textured_ply), "--export-type", "ply", "--max-threads", str(max_threads)],
        ]
        for command in stage_commands:
            commands.append(command)
            _run(command, scene_dir, log)
        mesh_header = mesh_ply.read_text(encoding="ascii", errors="replace").split("end_header", 1)[0]
        face_match = re.search(r"^element face (\d+)$", mesh_header, flags=re.MULTILINE)
        if face_match is None or int(face_match.group(1)) == 0:
            raise RuntimeError(f"OpenMVS produced an empty {capture} mesh: {mesh_ply}")
        ply = scene_dir / "scene_dense.ply"
        if not ply.is_file():
            # OpenMVS versions differ slightly on whether the fused PLY follows
            # the input scene basename or the output scene basename.
            candidates = sorted(scene_dir.glob("*.ply"))
            if candidates:
                ply = candidates[0]
        counts[f"{capture}_dense_ply"] = str(ply.resolve()) if ply.is_file() else None
        counts[f"{capture}_textured_mesh"] = str(textured_ply.resolve()) if textured_ply.is_file() else None

    candidates = json.loads(Path(object_report).read_text(encoding="utf-8"))
    object_pairs = []
    for candidate in candidates.get("candidates", []):
        review = candidate.get("review", {})
        if candidate.get("candidate_type") != "same_object_reviewed" or not (
            review.get("same_object") and review.get("geometry_accepted")
        ):
            continue
        before = candidate["before"]["centroid_xyz_colmap"]
        after = candidate["after"]["centroid_xyz_colmap"]
        object_pairs.append({
            "label": candidate.get("label", "object"),
            "before_xyz_colmap": before,
            "after_xyz_colmap": after,
            "displacement_map_units": float(np.linalg.norm(np.asarray(after) - np.asarray(before))),
            "estimated_displacement_m": (
                float(np.linalg.norm(np.asarray(after) - np.asarray(before))) * meters_per_map_unit
                if meters_per_map_unit is not None else None
            ),
            "note": "provisional automatic multiview mask-center anchors; map scale is not metric unless calibrated separately",
        })
    comparison_ply = output / "before_after_object_comparison.ply"
    _write_comparison_ply(
        output / "before/scene_textured.ply",
        output / "after/scene_textured.ply",
        object_pairs,
        comparison_ply,
    )
    counts["comparison_ply"] = str(comparison_ply)
    comparison_html = output / "before_after_object_comparison.html"
    _write_comparison_html(comparison_ply, comparison_html, object_pairs)
    counts["comparison_html"] = str(comparison_html)
    viewer_commands = [
        [str(tool["Viewer"]), "--input-file", str(output / capture / "scene_dense.mvs"), "--geometry-file", str(output / capture / "scene_textured.ply")]
        for capture in ("before", "after")
    ]
    result = {
        "schema_version": 1,
        "method": "OpenMVS CPU depth-map estimation and fusion (fusion-mode 0), separate per-capture scenes",
        "coordinate_frame": "shared_before_colmap_map",
        "metric_scale": meters_per_map_unit is not None,
        "meters_per_map_unit": meters_per_map_unit,
        "threads": max_threads,
        "counts": counts,
        "object_movement": object_pairs,
        "commands": commands,
        "viewer_commands": viewer_commands,
        "comparison_legend": "browser preview: blue before mesh; orange after mesh; green old center; red new center; yellow connector; anchors are illustrative, not measured object extents",
        "limitations": [
            "CPU depth-map estimation can be slow and image-based matching may leave holes or artifacts.",
            ("The models share the COLMAP coordinate frame and use a provisional per-run metric scale."
             if meters_per_map_unit is not None else "The models share the COLMAP coordinate frame but are not metric-scaled."),
            "Object movement is shown by provisional automatically matched center anchors, not mesh-derived tracking.",
        ],
        "log": str(log.resolve()),
    }
    report_path = output / "openmvs_reconstruction.json"
    report_path.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    return {"output_dir": str(output), "report": str(report_path), **counts,
            "object_movement": object_pairs, "comparison_ply": str(comparison_ply),
            "comparison_html": str(comparison_html),
            "viewer_commands": result["viewer_commands"]}
