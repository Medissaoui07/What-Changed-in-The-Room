@dataclass
class _SparsePoint:
    xyz: tuple[float, float, float]
    rgb: tuple[int, int, int]
    error: float
    track: list[tuple[int, int]]


def _read_sparse_points(path: Path) -> dict[int, _SparsePoint]:
    points: dict[int, _SparsePoint] = {}
    with path.open("rb") as stream:
        count, = struct.unpack("<Q", stream.read(8))
        for _ in range(count):
            point_id, x, y, z, red, green, blue, error, track_length = struct.unpack(
                "<QdddBBBdQ", stream.read(struct.calcsize("<QdddBBBdQ"))
            )
            track = [struct.unpack("<ii", stream.read(8)) for _ in range(track_length)]
            points[int(point_id)] = _SparsePoint(
                (x, y, z), (red, green, blue), error, track
            )
    return points


def _read_images(path: Path) -> dict[str, dict[str, object]]:
    images: dict[str, dict[str, object]] = {}
    with path.open("rb") as stream:
        count, = struct.unpack("<Q", stream.read(8))
        for _ in range(count):
            image_id, = struct.unpack("<i", stream.read(4))
            quaternion = np.asarray(struct.unpack("<4d", stream.read(32)), dtype=np.float64)
            translation = np.asarray(struct.unpack("<3d", stream.read(24)), dtype=np.float64)
            camera_id, = struct.unpack("<i", stream.read(4))
            name_bytes = bytearray()
            while True:
                char = stream.read(1)
                if not char:
                    raise ValueError("truncated COLMAP image name")
                if char == b"\0":
                    break
                name_bytes.extend(char)
            observation_count, = struct.unpack("<Q", stream.read(8))
            observations = [
                struct.unpack("<ddq", stream.read(24))
                for _ in range(observation_count)
            ]
            name = name_bytes.decode("utf-8")
            images[name] = {
                "image_id": image_id,
                "camera_id": camera_id,
                "quaternion": quaternion,
                "translation": translation,
                "points2d": np.asarray([(x, y) for x, y, _point_id in observations], dtype=np.float32).reshape(-1, 2),
                "point3d_ids": np.asarray([point_id for _x, _y, point_id in observations], dtype=np.int64),
            }
    return images


def _capture_for_image(name: str) -> str:
    return "after" if name.startswith("wcr_after_") else "before"


def _source_frame(name: str, capture: str) -> str:
    if capture == "after":
        match = re.fullmatch(r"wcr_after_\d+_(.+)", name)
        if match is None:
            raise ValueError(f"cannot map localized COLMAP image to an after frame: {name}")
        return match.group(1)
    return name


def _camera_intrinsics(camera: dict[str, object]) -> tuple[np.ndarray, np.ndarray]:
    matrix = camera["matrix"]
    distortion = camera["distortion"]
    assert isinstance(matrix, np.ndarray) and isinstance(distortion, np.ndarray)
    return matrix, distortion


def _write_capture_input(
    capture: str,
    model_dir: Path,
    source_dir: Path,
    destination: Path,
    cameras: dict[int, dict[str, object]],
    images: dict[str, dict[str, object]],
    points: dict[int, _SparsePoint],
) -> int:
    selected = [name for name in images if _capture_for_image(name) == capture]
    if len(selected) < 3:
        raise ValueError(f"only {len(selected)} registered {capture} views in {model_dir}; need at least 3")
    sparse_dir, image_dir = destination / "sparse", destination / "images"
    sparse_dir.mkdir(parents=True)
    image_dir.mkdir(parents=True)

    camera_ids = sorted({int(images[name]["camera_id"]) for name in selected})
    camera_new: dict[int, tuple[int, int, int, float, float, float, float]] = {}
    camera_rows = ["# COLMAP text model generated by wcr OpenMVS CPU pipeline"]
    for new_id, camera_id in enumerate(camera_ids, start=1):
        camera = cameras[camera_id]
        width, height = int(camera["width"]), int(camera["height"])
        matrix, distortion = _camera_intrinsics(camera)
        new_matrix, _roi = cv2.getOptimalNewCameraMatrix(
            matrix, distortion, (width, height), 0.0, (width, height)
        )
        camera_new[camera_id] = (
            new_id, width, height,
            float(new_matrix[0, 0]), float(new_matrix[1, 1]),
            float(new_matrix[0, 2]), float(new_matrix[1, 2]),
        )
        camera_rows.append(
            f"{new_id} PINHOLE {width} {height} "
            f"{new_matrix[0, 0]:.12g} {new_matrix[1, 1]:.12g} "
            f"{new_matrix[0, 2]:.12g} {new_matrix[1, 2]:.12g}"
        )
    (sparse_dir / "cameras.txt").write_text("\n".join(camera_rows) + "\n", encoding="utf-8")

    image_ids = {name: index for index, name in enumerate(selected, start=1)}
    point_tracks: dict[int, list[tuple[int, int]]] = {}
    image_data: dict[str, tuple[list[tuple[float, float]], list[int]]] = {}
    for name in selected:
        pose = images[name]
        camera_id = int(pose["camera_id"])
        camera = cameras[camera_id]
        source_name = _source_frame(name, capture)
        source_path = source_dir / source_name
        if not source_path.is_file():
            raise FileNotFoundError(f"registered image {name} maps to missing source frame {source_path}")
        image = cv2.imread(str(source_path), cv2.IMREAD_COLOR)
        if image is None:
            raise ValueError(f"could not decode source image {source_path}")
        width, height = int(camera["width"]), int(camera["height"])
        if image.shape[1] != width or image.shape[0] != height:
            raise ValueError(
                f"image size mismatch for {source_path}: {image.shape[1]}x{image.shape[0]}, "
                f"COLMAP expects {width}x{height}"
            )
        matrix, distortion = _camera_intrinsics(camera)
        new_camera = camera_new[camera_id]
        new_matrix = np.asarray([
            [new_camera[3], 0.0, new_camera[5]],
            [0.0, new_camera[4], new_camera[6]],
            [0.0, 0.0, 1.0],
        ], dtype=np.float64)
        undistorted = cv2.undistort(image, matrix, distortion, None, new_matrix)
        cv2.imwrite(str(image_dir / name), undistorted, [cv2.IMWRITE_JPEG_QUALITY, 95])

        keypoints = pose.get("points2d")
        point_ids = pose.get("point3d_ids")
        if not isinstance(keypoints, np.ndarray) or not isinstance(point_ids, np.ndarray):
            raise ValueError(f"COLMAP image parser did not provide observations for {name}")
        if len(keypoints):
            undistorted_xy = cv2.undistortPoints(
                keypoints.reshape(-1, 1, 2).astype(np.float32),
                matrix, distortion, P=new_matrix,
            ).reshape(-1, 2)
        else:
            undistorted_xy = np.empty((0, 2), dtype=np.float32)
        image_data[name] = (undistorted_xy.tolist(), point_ids.astype(np.int64).tolist())
    # Keep only 3D points with observations in at least two images from this
    # capture; this both bounds the initial cloud and prevents cross-capture
    # tracks from leaking chair geometry into the other reconstruction.
    for name in selected:
        xy, point_ids = image_data[name]
        image_id = image_ids[name]
        for point2d_index, point_id in enumerate(point_ids):
            if point_id >= 0:
                point_tracks.setdefault(int(point_id), []).append((image_id, point2d_index))
    kept_tracks = {
        point_id: track for point_id, track in point_tracks.items()
        if point_id in points and len(track) >= 2
    }
    keep_ids = set(kept_tracks)

    # Each image's second text row contains (x, y, point3D_id) triplets.
    image_rows = ["# COLMAP text model generated by wcr OpenMVS CPU pipeline"]
    for name in selected:
        pose = images[name]
        q, t = pose["quaternion"], pose["translation"]
        camera_row_id = camera_new[int(pose["camera_id"])][0]
        image_rows.append(
            f"{image_ids[name]} {q[0]:.17g} {q[1]:.17g} {q[2]:.17g} {q[3]:.17g} "
            f"{t[0]:.17g} {t[1]:.17g} {t[2]:.17g} {camera_row_id} {name}"
        )
        xy, point_ids = image_data[name]
        image_rows.append(" ".join(
            f"{pixel[0]:.6f} {pixel[1]:.6f} {point_id if point_id in keep_ids else -1}"
            for pixel, point_id in zip(xy, point_ids)
        ))
    (sparse_dir / "images.txt").write_text("\n".join(image_rows) + "\n", encoding="utf-8")

    point_rows = ["# COLMAP text model generated by wcr OpenMVS CPU pipeline"]
    for point_id in sorted(keep_ids):
        point = points[point_id]
        track = kept_tracks[point_id]
        track_text = " ".join(f"{image_id} {point2d_id}" for image_id, point2d_id in track)
        point_rows.append(
            f"{point_id} {point.xyz[0]:.12g} {point.xyz[1]:.12g} {point.xyz[2]:.12g} "
            f"{point.rgb[0]} {point.rgb[1]} {point.rgb[2]} {point.error:.8g} {track_text}"
        )
    (sparse_dir / "points3D.txt").write_text("\n".join(point_rows) + "\n", encoding="utf-8")
    return len(keep_ids)


def _find_tool(binary_dir: Path, name: str) -> Path:
    candidates = [binary_dir / name, *binary_dir.rglob(name)]
    for candidate in candidates:
        if candidate.is_file() and candidate.stat().st_mode & 0o111:
            return candidate
    raise FileNotFoundError(f"OpenMVS executable {name} was not found under {binary_dir}")


def _run(command: list[str], cwd: Path, log: Path) -> None:
    with log.open("a", encoding="utf-8") as stream:
        stream.write("$ " + " ".join(command) + "\n")
        stream.flush()
        result = subprocess.run(command, cwd=cwd, stdout=stream, stderr=subprocess.STDOUT, text=True)
    if result.returncode:
        tail = log.read_text(encoding="utf-8", errors="replace")[-6000:]
        raise RuntimeError(f"OpenMVS command failed ({result.returncode}): {' '.join(command)}\n{tail}")


def _read_textured_ply(path: Path) -> tuple[list[tuple[float, float, float]], list[tuple[int, int, int]]]:
    """Read OpenMVS's binary PLY vertices/faces, ignoring per-face UVs."""
    with path.open("rb") as stream:
        header: list[str] = []
        while True:
            line = stream.readline().decode("ascii").strip()
            header.append(line)
            if line == "end_header":
                break
        if "format binary_little_endian 1.0" not in header:
            raise ValueError(f"expected binary little-endian PLY: {path}")
        vertex_count = int(next(line.split()[-1] for line in header if line.startswith("element vertex ")))
        face_count = int(next(line.split()[-1] for line in header if line.startswith("element face ")))
        if [line for line in header if line.startswith("property ")][:3] != [
            "property float32 x", "property float32 y", "property float32 z"
        ]:
            raise ValueError(f"unsupported vertex layout in {path}")
        vertices = [struct.unpack("<fff", stream.read(12)) for _ in range(vertex_count)]
        faces: list[tuple[int, int, int]] = []
        for _ in range(face_count):
            size, = struct.unpack("<B", stream.read(1))
            indices = struct.unpack(f"<{size}I", stream.read(4 * size))
            if size >= 3:
                faces.append((indices[0], indices[1], indices[2]))
            if "property list uint8 float32 texcoord" in header:
                uv_size, = struct.unpack("<B", stream.read(1))
                stream.seek(4 * uv_size, 1)
        return vertices, faces


def _append_sphere(
    vertices: list[tuple[float, float, float]],
    faces: list[tuple[int, int, int]],
    center: np.ndarray,
    radius: float,
    segments: int,
    rings: int,
) -> None:
    start = len(vertices)
    for ring in range(rings + 1):
        phi = np.pi * ring / rings
        for segment in range(segments):
            theta = 2 * np.pi * segment / segments
            point = center + radius * np.asarray([
                np.sin(phi) * np.cos(theta), np.sin(phi) * np.sin(theta), np.cos(phi)
            ])
            vertices.append(tuple(float(value) for value in point))
    for ring in range(rings):
        for segment in range(segments):
            a = start + ring * segments + segment
            b = start + ring * segments + (segment + 1) % segments
            c = start + (ring + 1) * segments + segment
            d = start + (ring + 1) * segments + (segment + 1) % segments
            faces.extend(((a, c, b), (b, c, d)))


def _append_cylinder(
    vertices: list[tuple[float, float, float]],
    faces: list[tuple[int, int, int]],
    start_point: np.ndarray,
    end_point: np.ndarray,
    radius: float,
    segments: int = 8,
) -> None:
    direction = end_point - start_point
    direction /= np.linalg.norm(direction)
    axis = np.cross(direction, np.asarray([0.0, 0.0, 1.0]))
    if np.linalg.norm(axis) < 1e-6:
        axis = np.cross(direction, np.asarray([0.0, 1.0, 0.0]))
    axis /= np.linalg.norm(axis)
    other = np.cross(direction, axis)
    base = len(vertices)
    for center in (start_point, end_point):
        for index in range(segments):
            angle = 2 * np.pi * index / segments
            point = center + radius * (np.cos(angle) * axis + np.sin(angle) * other)
            vertices.append(tuple(float(value) for value in point))
    for index in range(segments):
        a, b = base + index, base + (index + 1) % segments
        c, d = base + segments + index, base + segments + (index + 1) % segments
        faces.extend(((a, b, c), (b, d, c)))


def _write_comparison_ply(
    before_path: Path,
    after_path: Path,
    movements: list[dict[str, object]],
    output_path: Path,
) -> None:
    before_vertices, before_faces = _read_textured_ply(before_path)
    after_vertices, after_faces = _read_textured_ply(after_path)
    vertices = before_vertices + after_vertices
    faces = before_faces + [
        (a + len(before_vertices), b + len(before_vertices), c + len(before_vertices))
        for a, b, c in after_faces
    ]
    vertex_colors = [(48, 130, 245)] * len(before_vertices) + [(245, 112, 50)] * len(after_vertices)
    marker_colors: list[tuple[int, int, int]] = []
    if movements:
        bounds = np.ptp(np.asarray(vertices), axis=0)
        radius = max(float(np.linalg.norm(bounds)) * 0.008, 0.025)
        for movement in movements:
            before = np.asarray(movement["before_xyz_colmap"], dtype=np.float64)
            after = np.asarray(movement["after_xyz_colmap"], dtype=np.float64)
            _append_sphere(vertices, faces, before, radius, 12, 8)
            vertex_colors.extend([(55, 235, 115)] * (len(vertices) - len(vertex_colors)))
            _append_sphere(vertices, faces, after, radius, 12, 8)
            vertex_colors.extend([(255, 65, 75)] * (len(vertices) - len(vertex_colors)))
            _append_cylinder(vertices, faces, before, after, radius * 0.22)
            vertex_colors.extend([(255, 220, 45)] * (len(vertices) - len(vertex_colors)))
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("wb") as stream:
        stream.write(("\n".join([
            "ply", "format binary_little_endian 1.0",
            "comment before mesh blue; after mesh orange; reviewed object before green; after red; connector yellow",
            f"element vertex {len(vertices)}", "property float x", "property float y", "property float z",
            "property uchar red", "property uchar green", "property uchar blue",
            f"element face {len(faces)}", "property list uchar uint vertex_indices", "end_header", "",
        ])).encode("ascii"))
        for point, color in zip(vertices, vertex_colors):
            stream.write(struct.pack("<fffBBB", *point, *color))
        for face in faces:
            stream.write(struct.pack("<BIII", 3, *face))


